import SwiftUI
import os

/// Clipboard history (ARCHITECTURE §8, D7, D7a–D7c): the last `limit` text, link and image items, newest first, in
/// memory, never logged. Text and links are saved to disk only if the user turns that on in Settings (D34). Nothing is
/// read until the user turns history on in the tab. Contents are read in the background only under Always Allow; under Ask a read waits for the user's "Add Clipboard" click (D7c).
@MainActor
@Observable
final class ClipboardModule: NotchModule {
    let id = "clipboard"
    let title: LocalizedStringResource = "Clipboard"
    let systemImage = "doc.on.clipboard"
    let hasCompactContent = false

    static let limit = 25
    static let maxImageBytes = 10_000_000
    static let maxTotalImageBytes = 50_000_000
    /// UTF-16 units, about 1–2 MB. Longer text is skipped rather than cut, so copy-back never returns half (M2).
    static let maxTextLength = 1_000_000
    /// nspasteboard.org markers: passwords, one-off and generated items never enter history (D7).
    static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        // Older markers from the same list, still written by some password managers and text expanders (L1).
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.agilebits.onepassword"),
        .init("com.typeit4me.clipping"),
        .init("Pasteboard generator type"),
        .init("net.antelle.keeweb"),
    ]

    /// The user turned history on in the tab. Saved, so it is asked once.
    private(set) var isOn: Bool
    /// Settings › Privacy: keep text and links in `storeURL` across relaunches (D34). Off by default (D7).
    private(set) var savesToDisk: Bool
    private(set) var access = PasteboardAccess.ask
    /// Newest first.
    private(set) var items: [ClipboardItem] = []
    /// Under Ask, something was copied since the last read, so the tab offers "Add Clipboard" (D7c).
    private(set) var hasUnreadChange = false
    /// Always Allow was chosen while DropNotch ran. It may apply only after a relaunch (D7c), so it is treated as Ask
    /// until then, and the tab says so (code-reviewer W1).
    private(set) var needsRelaunch = false

    @ObservationIgnored private let pasteboard: any Pasteboard
    @ObservationIgnored private let defaults: UserDefaults
    @ObservationIgnored private let storeURL: URL
    @ObservationIgnored private var isRunning = false
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount: Int?
    @ObservationIgnored private var sleepObservers: [NSObjectProtocol] = []
    /// Whether Always Allow held when the module was made, at launch. Reading the setting reads no content.
    @ObservationIgnored private let allowedAtLaunch: Bool

    private static let isOnKey = "clipboard.historyOn"
    private static let savesToDiskKey = "clipboard.savesToDisk"

    /// `pasteboard`, `defaults` and `storeURL` are internal for tests.
    init(pasteboard: any Pasteboard = NSPasteboard.general, defaults: UserDefaults = .standard,
         storeURL: URL = .applicationSupportDirectory.appending(path: "DropNotch/clipboard.json")) {
        self.pasteboard = pasteboard
        self.defaults = defaults
        self.storeURL = storeURL
        isOn = defaults.bool(forKey: Self.isOnKey)
        savesToDisk = defaults.bool(forKey: Self.savesToDiskKey)
        allowedAtLaunch = pasteboard.access == .allowed
    }

    func compactView(slot: CompactSlot) -> AnyView { AnyView(EmptyView()) }

    func expandedView() -> AnyView { AnyView(ClipboardExpandedView(module: self)) }

    func settingsView() -> AnyView { AnyView(EmptyView()) }

    func start() {
        guard !isRunning else { return }
        isRunning = true
        // The poll pauses while the screens sleep (D7, ARCHITECTURE §9).
        let center = NSWorkspace.shared.notificationCenter
        sleepObservers = [
            center.addObserver(forName: NSWorkspace.screensDidSleepNotification, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.stopTimer() }
            },
            center.addObserver(forName: NSWorkspace.screensDidWakeNotification, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.watch() }
            },
        ]
        if isOn, savesToDisk { load() }
        watch()
    }

    /// Stops the poll and forgets the history in memory (module turned off, app quit). A saved file stays.
    func stop() {
        isRunning = false
        stopTimer()
        sleepObservers.forEach(NSWorkspace.shared.notificationCenter.removeObserver)
        sleepObservers = []
        items = []
        hasUnreadChange = false
        lastChangeCount = nil
    }

    /// The tab's "Turn On" button: the user's consent to watch the clipboard.
    func turnOn() {
        isOn = true
        defaults.set(true, forKey: Self.isOnKey)
        watch()
    }

    /// Settings › Privacy: stops the poll, forgets the history and deletes the saved file. The tab offers Turn On again.
    func turnOff() {
        isOn = false
        defaults.set(false, forKey: Self.isOnKey)
        stopTimer()
        items = []
        hasUnreadChange = false
        lastChangeCount = nil
        // Keeping is turned off too, so turning history on again never resumes writing to disk unasked (security-auditor L3).
        setSavesToDisk(false)
    }

    /// Settings › Privacy: turning it on saves the current history; turning it off deletes the file (D34).
    func setSavesToDisk(_ on: Bool) {
        savesToDisk = on
        defaults.set(on, forKey: Self.savesToDiskKey)
        if on { save() } else { deleteStore() }
    }

    /// The tab appeared: picks up a change in System Settings, and restarts a poll stopped by Always Deny.
    func refresh() {
        guard isOn, isRunning else { return }
        access = currentAccess()
        watch()
    }

    /// Starts the poll if history is on and access isn't denied.
    private func watch() {
        guard isOn, isRunning, timer == nil else { return }
        access = currentAccess()
        guard access != .denied else { return }
        // 0.5 s with 0.25 s tolerance, so the system can batch the wake (D7). No notification exists for a change.
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .default)
        self.timer = timer
        Logger.clipboard.debug("Clipboard poll started")
        tick()
    }

    /// `Pasteboard.access`, except that Always Allow is trusted only if it held at launch: a background read that
    /// macOS still treats as Ask would freeze the notch behind the alert (D7c).
    private func currentAccess() -> PasteboardAccess {
        let access = pasteboard.access
        needsRelaunch = access == .allowed && !allowedAtLaunch
        return needsRelaunch ? .ask : access
    }

    private func stopTimer() {
        timer?.invalidate()
        timer = nil
    }

    /// One poll: only `changeCount` until it changes, then the access check, then a read only under Always Allow (D7c).
    /// Internal so tests can drive it without the timer.
    func tick() {
        // Consent first, whoever calls this.
        guard isOn else { return }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let previous = access
        // Checked before every read: denied reads fail silently (D7a).
        access = currentAccess()
        if access != previous { Logger.clipboard.info("Clipboard access changed: \(String(describing: self.access), privacy: .public)") }
        switch access {
        case .allowed: capture()
        case .ask: hasUnreadChange = true
        case .denied: stopTimer()
        }
    }

    /// The tab's "Add Clipboard" button under Ask. The read may raise the macOS alert and block until it is answered;
    /// the user asked for it (D7c).
    func addCurrent() {
        hasUnreadChange = false
        lastChangeCount = pasteboard.changeCount
        capture()
        access = currentAccess()
    }

    /// Puts an item back on the clipboard and moves it to the top.
    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let text), .link(let text): pasteboard.setString(text, forType: .string)
        case .image(let data, let type): pasteboard.setData(data, forType: type)
        }
        // DropNotch's own write isn't read back: no alert under Ask, and the item is already in the history.
        lastChangeCount = pasteboard.changeCount
        hasUnreadChange = false
        add(item)
    }

    /// The history filtered by a search, matched case- and diacritic-insensitively. Images only show unfiltered.
    func items(matching query: String) -> [ClipboardItem] {
        let query = query.trimmingCharacters(in: .whitespaces)
        guard !query.isEmpty else { return items }
        return items.filter { $0.text?.localizedStandardContains(query) == true }
    }

    /// The tab's and Settings' "Clear" button: forgets the history and deletes the saved file, without turning it off.
    /// Works while the module is off too, so Settings can delete a file left from an earlier run.
    func clear() {
        items = []
        deleteStore()
    }

    private func capture() {
        let count = pasteboard.changeCount
        // A change mid-read could pair one item's types with another's content, such as a password whose concealed
        // marker was never seen (security-auditor L2).
        guard let content = readContent(), pasteboard.changeCount == count else { return }
        add(ClipboardItem(content))
    }

    /// Cheapest first (D7a): `types`, skipping marked items, then the content.
    private func readContent() -> ClipboardItem.Content? {
        guard let types = pasteboard.types,
              !types.contains(where: Self.skippedTypes.contains),
              // A Finder copy is a file, which is the tray's job; its icon would show up here as an image.
              !types.contains(.fileURL) else { return nil }
        // Text first: Office and similar apps put a picture of the text alongside it.
        if types.contains(.string), let text = pasteboard.string(forType: .string),
           text.utf16.count <= Self.maxTextLength, text.contains(where: { !$0.isWhitespace }) {
            return ClipboardItem.isLink(text) ? .link(text) : .text(text)
        }
        guard let type = [NSPasteboard.PasteboardType.png, .tiff].first(where: types.contains),
              let data = pasteboard.data(forType: type), data.count <= Self.maxImageBytes,
              ClipboardItem.isAcceptableImage(data) else { return nil }
        return .image(data, type)
    }

    /// Newest first, without duplicates, at most `limit` items and `maxTotalImageBytes` of images (oldest images go first).
    private func add(_ item: ClipboardItem) {
        items.removeAll { $0.content == item.content }
        items.insert(item, at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
        var imageBytes = 0
        items = items.filter {
            guard case .image(let data, _) = $0.content else { return true }
            imageBytes += data.count
            return imageBytes <= Self.maxTotalImageBytes
        }
        save()
    }

    // MARK: Saved history (D34)

    /// The file is a JSON array of the text and link items' text, newest first. Images stay in memory only. Only while
    /// running: a stopped module holds no items, and saving then would wipe the file it loads on the next start.
    // shortcut: rewritten on the main thread on every copy; fine for 25 typical items, move off the main thread if
    // multi-megabyte text copies stall the notch.
    private func save() {
        guard savesToDisk, isOn, isRunning else { return }
        do {
            // 0700 if it creates the folder, so the moment the new file is 0644 (below) exposes nothing (security-auditor L2).
            try FileManager.default.createDirectory(at: storeURL.deletingLastPathComponent(), withIntermediateDirectories: true,
                                                    attributes: [.posixPermissions: 0o700])
            try JSONEncoder().encode(items.compactMap(\.text)).write(to: storeURL, options: .atomic)
        } catch {
            Logger.clipboard.error("Clipboard write failed: \((error as NSError).domain, privacy: .public) \((error as NSError).code)")
            return
        }
        // An atomic write replaces the file, so its permissions and backup flag are set again each time, separately, so
        // one failing doesn't skip the other.
        do {
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: storeURL.path)
        } catch {
            Logger.clipboard.error("Clipboard file permissions failed: \((error as NSError).domain, privacy: .public) \((error as NSError).code)")
        }
        do {
            var store = storeURL
            var values = URLResourceValues()
            values.isExcludedFromBackup = true
            try store.setResourceValues(values)
        } catch {
            Logger.clipboard.error("Clipboard backup exclusion failed: \((error as NSError).domain, privacy: .public) \((error as NSError).code)")
        }
    }

    /// The file is untrusted input (any same-user process can edit it): the same text rules as a copy apply.
    private func load() {
        // 25 texts at the length cap, as UTF-8 JSON: well under 100 MB. A bigger file isn't ours to read in full.
        // A regular file only: a symlink reports its own size, and a FIFO would block the read forever (security-auditor L1).
        guard let values = try? storeURL.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey]),
              values.isRegularFile == true, let size = values.fileSize, size <= 100_000_000,
              let data = try? Data(contentsOf: storeURL) else { return }
        guard let texts = try? JSONDecoder().decode([String].self, from: data) else {
            Logger.clipboard.error("Clipboard file unreadable")
            return
        }
        items = texts
            .filter { $0.utf16.count <= Self.maxTextLength && $0.contains(where: { !$0.isWhitespace }) }
            .prefix(Self.limit)
            .map { ClipboardItem(ClipboardItem.isLink($0) ? .link($0) : .text($0)) }
    }

    private func deleteStore() {
        do {
            try FileManager.default.removeItem(at: storeURL)
        } catch CocoaError.fileNoSuchFile {
        } catch {
            Logger.clipboard.error("Clipboard file delete failed: \((error as NSError).domain, privacy: .public) \((error as NSError).code)")
        }
    }
}
